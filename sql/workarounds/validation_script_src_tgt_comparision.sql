        IF(t.FirstFutileDate             IS DISTINCT FROM s.FirstFutileDate,             'FirstFutileDate',             NULL),
        IF(t.FirstFutileRF               IS DISTINCT FROM s.FirstFutileRF,               'FirstFutileRF',               NULL),
        IF(t.FirstFutileCF               IS DISTINCT FROM s.FirstFutileCF,               'FirstFutileCF',               NULL),
        IF(t.FirstFutileScanType         IS DISTINCT FROM s.FirstFutileScanType,         'FirstFutileScanType',         NULL),
        IF(t.FirstFutileScanStatus       IS DISTINCT FROM s.FirstFutileScanStatus,       'FirstFutileScanStatus',       NULL),
        IF(t.FirstReceivedOrFirstScanDate IS DISTINCT FROM s.FirstReceivedOrFirstScanDate, 'FirstReceivedOrFirstScanDate', NULL)      ]) AS col
      WHERE col IS NOT NULL
    ) AS mismatch_columns

  FROM target t
  INNER JOIN source s
    ON t.LabelNo = s.LabelNo
)

SELECT
  LabelNo,
  target_row,
  source_row,
  mismatch_columns,
  ARRAY_TO_STRING(mismatch_columns, ', ') AS mismatch_columns_str,
  IF(ARRAY_LENGTH(mismatch_columns) = 0, 'MATCH', 'MISMATCH') AS row_status
FROM compared;